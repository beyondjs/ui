import { test, after, beforeEach } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { Page } from './support/page.mjs';

/** Diff's drawing (0.11.2): files as regions named by their paths, headers in words, lines read with their prefix, gaps and folded runs from the input only, notes, the summary and the list of files, Copy path, Spanish. */
const page = new Page();
const ui = await import('@beyond-js/ui/dom');
const { Diff } = ui;
after(() => page.close());
beforeEach(() => page.reset());
const fixture = name => readFileSync(new URL(`./fixtures/diff/${name}.patch`, import.meta.url), 'utf8');
const mount = options => new Diff(options).mount(document.body);
const file = (diff, path) => [...diff.element.querySelectorAll('.bui-diff-file')].find(node => node.dataset.path === path);

test('each file is a region named by its path, with a heading holding the disclosure button: path, status in words and counts with their sentence', () => {
	const diff = mount({ patch: fixture('git') });
	const root = diff.element;
	assert.equal(root.tagName, 'SECTION');
	assert.equal(root.getAttribute('aria-label'), 'Changes');
	assert.equal(document.getElementById(root.getAttribute('aria-describedby')).textContent, 'Arrow keys move between files; ] and [ move between hunks.');
	const sections = [...root.querySelectorAll('section.bui-diff-file')];
	assert.deepEqual(sections.map(node => document.getElementById(node.getAttribute('aria-labelledby')).textContent), ['src/app.js', 'docs/notes.md', 'old/legacy.txt']);
	assert.deepEqual(sections.map(node => node.dataset.status), ['modified', 'added', 'deleted']);
	const app = sections[0];
	const toggle = app.querySelector('h3.bui-diff-heading > button.bui-diff-toggle');
	assert.equal(toggle.getAttribute('aria-expanded'), 'true');
	assert.ok(document.getElementById(toggle.getAttribute('aria-controls')) === app.querySelector('.bui-diff-body'));
	assert.ok(toggle.querySelector('.bui-diff-chevron svg[data-icon="chevron"]'), 'the chevron beside the words');
	assert.equal(app.querySelector('.bui-diff-dir').textContent, 'src/');
	assert.equal(app.querySelector('.bui-diff-name').textContent, 'app.js');
	assert.deepEqual(sections.map(node => node.querySelector('.bui-diff-status').textContent), ['Modified', 'Added', 'Deleted']);
	const count = app.querySelector('.bui-diff-count');
	assert.equal(count.querySelector('[aria-hidden="true"]').textContent, '+2 −1');
	assert.equal(count.querySelector('.bui-hidden').textContent, '2 added lines, 1 removed line');
	assert.equal(sections[2].querySelector('.bui-diff-count .bui-hidden').textContent, '0 added lines, 3 removed lines');
	assert.ok(app.hasAttribute('data-open'));
	diff.destroy();
});

